import { Link } from "react-router-dom";
import { NAV } from "../nav";
import { GAME } from "../lib/gameMeta";
import { GameIcon } from "../components/ui/GameIcon";
import { iconUrl } from "../lib/assets";
import { openQuickLookup } from "../components/QuickLookup";
import { crops, zombies, enemies, placeables, boosts, mutations, abilities, raids, epicBosses, questsFile, economy } from "../data";

const META: Record<string, { count?: number; note?: string }> = {
  "/crops": { count: crops.length },
  "/zombies": { count: zombies.length },
  "/enemies": { count: enemies.length },
  "/placeables": { count: placeables.length },
  "/boosts": { count: boosts.length },
  "/mutations": { count: mutations.length },
  "/abilities": { count: abilities.length },
  "/raids": { count: raids.length },
  "/epic-bosses": { count: epicBosses.length },
  "/quests": { count: questsFile.core.length + questsFile.reforged.length },
  "/calculator": { note: "Best build per stat" },
  "/pot-simulator": { note: "Combine two zombies" },
  "/leveling": { note: `${economy.maxLevel} levels` },
  "/progression": { note: "Unlock timeline" },
  "/about": { note: "How this is built" },
};

function Card({ to, label, icon, iconClass }: { to: string; label: string; icon: string; iconClass?: string }) {
  const m = META[to] ?? {};
  return (
    <Link
      to={to}
      className="group flex items-center gap-3 rounded-xl border border-border bg-surface p-3 transition-all hover:-translate-y-0.5 hover:border-primary hover:shadow-md"
    >
      <span className="grid h-14 w-14 shrink-0 place-items-center rounded-lg bg-surface-2 transition-colors group-hover:bg-primary/10">
        <GameIcon file={icon} alt="" size="lg" fallback="none" className={iconClass} />
      </span>
      <span className="min-w-0">
        <span className="block font-display text-base font-semibold leading-tight text-text">{label}</span>
        <span className="block text-xs text-muted">{m.count != null ? `${m.count} entries` : m.note}</span>
      </span>
    </Link>
  );
}

export function Home() {
  return (
    <div>
      {/* Hero */}
      <section className="mb-8 rounded-2xl border border-border bg-gradient-to-br from-primary/15 via-surface to-surface p-6 sm:p-9">
        <div className="max-w-2xl">
          <h1 className="flex flex-wrap items-center gap-x-3 font-display text-4xl font-bold tracking-tight sm:text-5xl">
            <span>
              Zombie Farm Reforged <span className="text-primary-strong">Wiki</span>
            </span>
            <img src={iconUrl("ZombieActorOldMcZombie.png") ?? ""} alt="Old McZombie" className="h-14 w-auto drop-shadow-sm sm:h-16" />
          </h1>
          <p className="mt-3 text-[15px] leading-relaxed text-muted">
            This is an autogenerated wiki from the game's{" "}
            <a href={GAME.repoUrl} target="_blank" rel="noreferrer" className="font-medium text-primary-strong underline decoration-primary/40 underline-offset-2">
              source code
            </a>
            . Use the cards below to browse, or hit <kbd className="rounded border border-border bg-surface px-1.5 py-0.5 text-xs font-semibold">Shift</kbd>
            +<kbd className="rounded border border-border bg-surface px-1.5 py-0.5 text-xs font-semibold">P</kbd> to open Quick Lookup and search
            for exactly what you're looking for.
          </p>

          <button
            onClick={openQuickLookup}
            className="mt-5 flex w-full max-w-md items-center gap-2 rounded-lg border border-border bg-surface px-3 py-2.5 text-left text-sm text-muted transition-colors hover:border-primary"
          >
            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true">
              <circle cx="11" cy="11" r="7" />
              <path d="m21 21-4.3-4.3" />
            </svg>
            Search crops, zombies, raids, mutations…
            <kbd className="ml-auto rounded border border-border px-1.5 py-0.5 text-[10px]">Shift + P</kbd>
          </button>
        </div>
      </section>

      {/* Browse */}
      {NAV.map((group) => (
        <section key={group.title} className="mb-7">
          <h2 className="mb-3 text-sm font-semibold uppercase tracking-wider text-muted">{group.title}</h2>
          <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3">
            {group.items.map((item) => (
              <Card key={item.to} to={item.to} label={item.label} icon={item.icon} iconClass={item.iconClass} />
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}
